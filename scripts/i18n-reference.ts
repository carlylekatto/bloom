import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { flatten } from "../src/i18n/catalog";

const root = join(import.meta.dir, "..");
const output = join(root, "docs", "TRANSLATION_REFERENCE.md");
const source = join(root, "src", "i18n", "locales", "en.json");
const labels: Record<string, string> = {
	ui: "Additional interface text",
	app: "Notch and system controls",
	settings: "Settings",
	common: "Shared controls",
	dock: "Dock",
	notch: "Notch",
	overlay: "Overlays",
	preview: "Settings previews",
	battery: "Battery status",
	weather: "Weather",
	featurePreview: "Settings previews",
	onboarding: "Welcome and setup",
	wifiPanel: "Wi-Fi panel",
	bluetoothPanel: "Bluetooth panel",
	connectedDevicesPanel: "Connected devices panel",
	connectedDevices: "Device groups",
	deviceLooks: "Device appearance",
	dockExtras: "Dock folders",
	batteryTooltip: "Battery tooltip",
	aboutTab: "Settings: About",
	generalTab: "Settings: General",
	appearanceTab: "Settings: Appearance",
	dockTab: "Settings: Dock",
	notchTab: "Settings: Notch",
	calendar: "Calendar and timer",
	commandCenter: "Command Center",
	music: "Music controls",
	previewDock: "Dock preview",
	previewMediaPlayer: "Music preview"
};

function heading(path: string) {
	const parts = path.split(".");
	if (parts[0] === "ui") parts.shift();
	return parts
		.map(
			(part) =>
				labels[part] ??
				part.replace(/([a-z])([A-Z])/g, "$1 $2").replace(/^./, (ch) => ch.toUpperCase())
		)
		.join(" → ");
}

function cell(text: string) {
	return text
		.replace(/&/g, "&amp;")
		.replace(/</g, "&lt;")
		.replace(/>/g, "&gt;")
		.replace(/\|/g, "&#124;")
		.replace(/`/g, "&#96;")
		.replace(/([\\*_[\]])/g, "\\$1")
		.replace(/\r?\n/g, "<br>");
}

export function renderReference(catalog: unknown) {
	const groups = new Map<string, [string, string][]>();
	for (const [key, text] of flatten(catalog)) {
		if (typeof text !== "string") throw new Error(`Invalid English message: ${key}`);
		const group = key.includes(".") ? key.slice(0, key.lastIndexOf(".")) : "common";
		if (!groups.has(group)) groups.set(group, []);
		groups.get(group)!.push([key, text]);
	}
	let result = `<!-- Generated from src/i18n/locales/en.json by bun run i18n:reference. Do not edit this file directly. -->
# English phrases to translate

Use this page as your reference when [contributing translations](../TRANSLATING.md). Choose one area and translate a few phrases at a time. You do not need to finish this list.

The **English text** is what you translate. The **Reference key** identifies the message for maintainers; you can copy it into your issue, but you do not need to understand it. Preserve placeholders such as \`{{count}}\` exactly. Use your browser's Find command to look for a phrase you saw in Bloom.

Headings follow the catalog's organization. Shared messages can appear on multiple screens; a screenshot or screen name helps when context is unclear. Entries ending in \`_one\` and \`_other\` are grammatical variants of the same message.

This page is generated from the [current English catalog](../src/i18n/locales/en.json), including text added since the latest release. Update the catalog rather than editing this reference. CI checks that the reference stays up to date.
`;
	for (const [group, entries] of groups) {
		result += `\n## ${heading(group)}\n\n| Reference key | English text |\n| --- | --- |\n`;
		for (const [key, text] of entries) result += `| \`${key}\` | ${cell(text)} |\n`;
	}
	return result;
}

if (import.meta.main) {
	const expected = renderReference(JSON.parse(readFileSync(source, "utf8")));
	if (process.argv.includes("--check")) {
		let actual = "";
		try {
			actual = readFileSync(output, "utf8").replace(/\r\n/g, "\n");
		} catch {
			/* report missing reference */
		}
		if (actual !== expected) {
			console.error(
				"English phrase reference is out of date. Run bun run i18n:reference and commit docs/TRANSLATION_REFERENCE.md."
			);
			process.exit(1);
		}
		console.log("English phrase reference is up to date.");
	} else {
		writeFileSync(output, expected);
		console.log("Updated docs/TRANSLATION_REFERENCE.md from the English catalog.");
	}
}
